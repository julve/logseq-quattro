import { readFileSync, writeFileSync } from 'node:fs';
const files = ['src/fonts.css', 'src/theme.css'];
const notices = ['LICENSE', 'licenses/RoamStudio-MIT.txt', 'licenses/iA-Writer-Quattro-OFL.md']
  .map(f => `/*\n${readFileSync(f, 'utf8').trim()}\n*/\n`).join('\n');
writeFileSync('custom.css', '/* Logseq Quattro — MIT; embedded iA Writer Quattro fonts — SIL OFL 1.1.\n * Generated by npm run build; edit src/ instead. */\n' + notices + files.map(f => readFileSync(f, 'utf8')).join('\n'));
console.log('Built custom.css (self-contained, no external requests)');
